nome = input('Digite o seu nome: ')
print(f'olá {nome}! Bem-vindo(a) ao mundo Python !') 
#'nome' é uma variável usada para guardar o valor digitado pelo usuário.
#input(), é usado para pedir ao usuário que digite uma informação.
#as aspas simples '' ou duplas "" são usadas para indicar que o que está dentro delas é uma string (texto).
#os parênteses () são usados para indicar que o que está dentro deles é uma informação que a função precisa para funcionar.
#o print() é usado para mostrar uma mensagem na tela.
# O f ativa a "formatação", permitindo usar variáveis entre chaves {}.
#as chaves {} são usadas para inserir o valor dentro do texto.
